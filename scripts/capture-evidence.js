import { randomBytes } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const base = new URL(process.env.API_BASE_URL ?? 'http://127.0.0.1:5000')
if (!['localhost', '127.0.0.1', '[::1]'].includes(base.hostname) || !['http:', 'https:'].includes(base.protocol)) {
  throw new Error('Run evidence capture against a local disposable API instance')
}
const suffix = randomBytes(5).toString('hex')
const password = randomBytes(18).toString('hex')
const entries = []

function redact(value) {
  return JSON.parse(JSON.stringify(value, (key, item) =>
    ['password', 'accessToken'].includes(key) ? '[redacted]' : item))
}

async function call(method, path, status, body, accessToken) {
  const response = await fetch(new URL(path, base), {
    method,
    redirect: 'error',
    signal: AbortSignal.timeout(10000),
    headers: {
      ...(body && { 'Content-Type': 'application/json' }),
      ...(accessToken && { Authorization: 'Bearer ' + accessToken })
    },
    body: body ? JSON.stringify(body) : undefined
  })
  const result = await response.json()
  assert.equal(response.status, status, method + ' ' + path)
  assert.equal(result.success, true)
  entries.push({
    request: { method, path, ...(accessToken && { authorization: 'Bearer [redacted]' }), ...(body && { body: redact(body) }) },
    response: { status: response.status, body: redact(result) }
  })
  return result
}

async function account(name) {
  const email = name.toLowerCase() + '-' + suffix + '@example.test'
  await call('POST', '/api/auth/register', 201, { name, email, password })
  const { data } = await call('POST', '/api/auth/login', 200, { email, password })
  return data
}

const owner = await account('Owner')
const assignee = await account('Assignee')
const { data: project } = await call('POST', '/api/projects', 201, { name: 'Release verification' }, owner.accessToken)
await call('GET', '/api/projects', 200, undefined, assignee.accessToken)
const createTask = title => call('POST', '/api/tasks', 201, {
  title, project_id: project.id, assigned_to: assignee.user.id, priority: 'High', due_date: '2027-01-15'
}, owner.accessToken)
const { data: first } = await createTask('Backend draft')
const { data: second } = await createTask('Backend review')
const { data: completed } = await createTask('Backend checklist')
const projectPath = '/api/projects/' + project.id
const taskPath = '/api/tasks/' + completed.id
await call('GET', projectPath, 200, undefined, assignee.accessToken)
await call('PUT', projectPath, 200, { description: 'Demo project' }, owner.accessToken)
await call('GET', taskPath, 200, undefined, assignee.accessToken)
const updated = await call('PUT', taskPath, 200, { status: 'Completed' }, assignee.accessToken)
assert.equal(updated.data.status, 'Completed')
const query = new URLSearchParams({ search: 'BACKEND', status: 'Pending', priority: 'High',
  assigned_to: assignee.user.id, project_id: project.id, limit: 1 })
for (const [page, expectedId] of [[1, second.id], [2, first.id]]) {
  query.set('page', page)
  const result = await call('GET', '/api/tasks?' + query, 200, undefined, assignee.accessToken)
  assert.deepEqual(result.pagination, { total: 2, page, limit: 1, totalPages: 2 })
  assert.deepEqual(result.data.map(task => task.id), [expectedId])
}
const dashboard = await call('GET', '/api/dashboard/stats', 200, undefined, assignee.accessToken)
assert.deepEqual(dashboard.data, { totalProjects: 1, totalTasks: 3,
  pendingTasks: 2, inProgressTasks: 0, completedTasks: 1, assignedToMe: 3 })
await call('DELETE', taskPath, 200, undefined, owner.accessToken)
await call('DELETE', projectPath, 200, undefined, owner.accessToken)
await writeFile(new URL('../docs/api-evidence.json', import.meta.url), JSON.stringify({
  source: 'Live HTTP requests generated by npm run evidence. Credentials and bearer tokens are redacted.',
  entries
}, null, 2) + '\n')
console.log(`Saved ${entries.length} verified HTTP requests to docs/api-evidence.json.`)
